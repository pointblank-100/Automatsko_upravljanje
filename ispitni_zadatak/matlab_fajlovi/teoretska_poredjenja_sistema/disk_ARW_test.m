Ts = 0.04; a = 0.87517; b = 0.09986; umax = 125;
Kc = 3; Ki = 10;                      % ???? ??? ? PLC-? ????? ARW ?????
hdr = 1;                              % ???? ?????? ???????? (0 ??? ?? ????)

% --- ????? ????? ---
[f, p] = uigetfile({'*.csv;*.txt','CSV / TXT'; '*.*','??? ???????'}, '??????? ARW ???? CSV');
if isequal(f,0), disp('???? ??????? ????.'); return; end
fname = fullfile(p, f);
% fname = 'ovde_upisi_ime_fajla.csv';   % <- ???????????

% --- ????????? (textscan, ?????? ???? ??????? NaN) ---
fid = fopen(fname, 'r');
if fid < 0, error('?? ???? ?? ??????? ????: %s', fname); end
first = fgetl(fid);                        % ???? ???, ????? ?? ????????? ??????
frewind(fid);
delim = ',';
if numel(strfind(first, ';')) > numel(strfind(first, ',')), delim = ';'; end
ncol = numel(strfind(first, delim)) + 1;
C = textscan(fid, repmat('%f', 1, ncol), 'Delimiter', delim, ...
             'HeaderLines', hdr, 'EmptyValue', NaN, 'CollectOutput', 1);
fclose(fid);
T = C{1};
if size(T,2) < 3, error('CSV ???? ????? ??? 3 ?????? (u, y, r)'); end
T = T(all(isfinite(T(:,end-2:end)),2), :);   % ????????? ???? u, y, r

u_plc = T(:,end-2); y_plc = T(:,end-1); r = T(:,end);
N = numel(r); t = (0:N-1)'*Ts;

% --- ??? ??????????: m=1 ??? ARW, m=2 ?? ARW ---
y_all = zeros(N,2); u_all = zeros(N,2);
for m = 1:2
    arw = (m == 2);
    ystat = 0; ustat = 0; yout = 0; ui = 0;
    for k = 1:N
        e = r(k) - yout;             % FB1 ???? y ?? ?????????? ???????
        ui = ui + Ki*Ts*e;
        if arw, ui = min(max(ui,0),umax); end
        u = Kc*e + ui;
        u = min(max(u,0),umax);
        ystat = a*ystat + b*ustat;   % FB_Plant
        yout = ystat; ustat = u;
        y_all(k,m) = yout; u_all(k,m) = u;
    end
end
y_no = y_all(:,1); u_no = u_all(:,1);
y_ar = y_all(:,2); u_ar = u_all(:,2);

% --- ?????? ???? u ?????? ?? umax ????? ???? ????????? ---
k_max  = find(r == max(r), 1);
k_drop = k_max - 1 + find(r(k_max:end) < max(r)/2, 1);
if ~isempty(k_drop)
    d_no = find(u_no(k_drop:end) < umax - 1e-6, 1) - 1;
    d_ar = find(u_ar(k_drop:end) < umax - 1e-6, 1) - 1;
    if isempty(d_no), d_no = N - k_drop + 1; end
    if isempty(d_ar), d_ar = N - k_drop + 1; end
    fprintf('u ?????? ?? %g ????? ???? r: arw=false %.2f s, arw=true %.2f s\n', ...
        umax, d_no*Ts, d_ar*Ts);
end

% --- ???????? ---
figure;
subplot(3,1,1)
plot(t,r,'k'); grid on; ylabel('r');
subplot(3,1,2)
plot(t,u_plc,'k',t,u_no,'r--',t,u_ar,'b--'); grid on; ylabel('u');
legend('Trace (PLC)','arw = false','arw = true','Location','best');
subplot(3,1,3)
plot(t,y_plc,'k',t,y_no,'r--',t,y_ar,'b--'); grid on; ylabel('y'); xlabel('t [s]');
legend('Trace (PLC)','arw = false','arw = true','Location','best');

fprintf('RMSE u vs Trace: arw=false %.4f, arw=true %.4f\n', ...
    sqrt(mean((u_no-u_plc).^2)), sqrt(mean((u_ar-u_plc).^2)));